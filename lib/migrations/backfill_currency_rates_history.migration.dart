var backfillCurrencyRatesHistoryMigration = MigrationDefinition(
  'backfill_currency_rates_history',
  () async {
    var databaseService = GetIt.instance.get<DatabaseService>();
    var db = databaseService.db;

    var movementResult = await db.rawQuery('SELECT MIN(creationDate) AS minDate FROM movements');
    var movementMin = movementResult.first['minDate'] as String?;
    if (movementMin == null) {
      logger.d('No movements found; skipping currency rates backfill');
      return;
    }
    var historyResult = await db.rawQuery('SELECT MIN(createdAt) AS minDate FROM currency_rates');
    var historyMin = historyResult.first['minDate'] as String?;
    if (historyMin == null) {
      logger.d('No currency rates history yet; skipping backfill');
      return;
    }

    var firstMovementDate = DateTime.parse(movementMin);
    var firstHistoryDate = DateTime.parse(historyMin);
    if (!firstMovementDate.isBefore(firstHistoryDate)) {
      logger.d('First movement is not older than the rate history; skipping backfill');
      return;
    }

    (String, double, double, double, double)? effective;
    var batch = db.batch();
    var inserted = 0;
    for (var rate in _historicRates) {
      var rateDate = DateTime.parse(rate.$1);
      if (!rateDate.isAfter(firstMovementDate)) {
        effective = rate;
        continue;
      }
      if (!rateDate.isBefore(firstHistoryDate)) {
        break;
      }
      batch.insert('currency_rates', _rateMap(rate.$1, rate.$2, rate.$3, rate.$4, rate.$5));
      inserted++;
    }
    if (effective != null) {
      batch.insert('currency_rates', _rateMap(firstMovementDate.toIso8601String(), effective.$2, effective.$3, effective.$4, effective.$5));
      inserted++;
    }
    if (inserted > 0) {
      await batch.commit(noResult: true);
    }
    logger.d('Backfilled $inserted currency rate rows from CSV history');
  }, () async {
    logger.e('Cannot down this migration');
  }
);

